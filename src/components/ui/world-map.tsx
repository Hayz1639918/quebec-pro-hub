// Convert lat/lng to x/y coordinates on the map
function latLngToXY(lat: number, lng: number) {
  const x = ((lng + 180) / 360) * 1000;
  const y = ((90 - lat) / 180) * 500;
  return { x, y };
}

// Generate curved path between two points
function generateCurvedPath(
  start: { x: number; y: number },
  end: { x: number; y: number }
) {
  const midX = (start.x + end.x) / 2;
  const midY = Math.min(start.y, end.y) - Math.abs(end.x - start.x) * 0.15;
  return `M ${start.x} ${start.y} Q ${midX} ${midY} ${end.x} ${end.y}`;
}

export default function WorldMap({ dots = [], lineColor = "#0ea5e9" }: WorldMapProps) {
  const worldDots = useMemo(() => generateWorldDots(), []);

  return (
    <div className="w-full h-full relative overflow-hidden">
      <svg
        viewBox="0 0 1000 500"
        className="w-full h-full"
        preserveAspectRatio="xMidYMid slice"
      >
        {/* Dotted world map */}
        <g>
          {worldDots.map((dot, i) => (
            <circle
              key={i}
              cx={dot.x}
              cy={dot.y}
              r="1.5"
              fill="#d1d5db"
              opacity="0.6"
            />
          ))}
        </g>

        {/* Connection lines */}
        <g>
          {dots.map((connection, index) => {
            const start = latLngToXY(connection.start.lat, connection.start.lng);
            const end = latLngToXY(connection.end.lat, connection.end.lng);
            const path = generateCurvedPath(start, end);

            return (
              <g key={index}>
                {/* Static line shadow */}
                <path
                  d={path}
                  fill="none"
                  stroke={lineColor}
                  strokeWidth="1.5"
                  strokeOpacity="0.3"
                  strokeLinecap="round"
                />
                
                {/* Animated line */}
                <motion.path
                  d={path}
                  fill="none"
                  stroke={lineColor}
                  strokeWidth="2"
                  strokeLinecap="round"
                  initial={{ pathLength: 0, opacity: 0 }}
                  animate={{ pathLength: 1, opacity: 1 }}
                  transition={{
                    duration: 1.5,
                    delay: index * 0.2,
                    ease: "easeOut",
                  }}
                />

                {/* Start point */}
                <motion.circle
                  cx={start.x}
                  cy={start.y}
                  r="4"
                  fill={lineColor}
                  initial={{ scale: 0 }}
                  animate={{ scale: 1 }}
                  transition={{ duration: 0.3, delay: index * 0.2 }}
                />
                
                {/* Start point ring */}
                <motion.circle
                  cx={start.x}
                  cy={start.y}
                  r="4"
                  fill="none"
                  stroke={lineColor}
                  strokeWidth="2"
                  initial={{ scale: 1, opacity: 0.8 }}
                  animate={{ scale: 2.5, opacity: 0 }}
                  transition={{
                    duration: 1.5,
                    delay: index * 0.2,
                    repeat: Infinity,
                    repeatDelay: 1,
                  }}
                />

                {/* End point */}
                <motion.circle
                  cx={end.x}
                  cy={end.y}
                  r="4"
                  fill={lineColor}
                  initial={{ scale: 0 }}
                  animate={{ scale: 1 }}
                  transition={{ duration: 0.3, delay: index * 0.2 + 1 }}
                />
                
                {/* End point ring */}
                <motion.circle
                  cx={end.x}
                  cy={end.y}
                  r="4"
                  fill="none"
                  stroke={lineColor}
                  strokeWidth="2"
                  initial={{ scale: 1, opacity: 0.8 }}
                  animate={{ scale: 2.5, opacity: 0 }}
                  transition={{
                    duration: 1.5,
                    delay: index * 0.2 + 1,
                    repeat: Infinity,
                    repeatDelay: 1,
                  }}
                />
              </g>
            );
          })}
        </g>
      </svg>
    </div>
  );
}
